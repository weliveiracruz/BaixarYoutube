export const STRINGS: Record<Language, Strings> = { "pt-BR": ptBR, en };

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && (LANGUAGES as readonly string[]).includes(value);
}

/** The text with {name} replaced. */
export function format(text: string, values: Record<string, string | number> = {}): string {
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in values ? String(values[name]) : m));
}

/** The label without "&" and the access key letter (lower case), or null. */
export function mnemonic(label: string): { text: string; key: string | null; index: number } {
  const index = label.indexOf("&");
  if (index < 0 || index === label.length - 1) return { text: label.replace("&", ""), key: null, index: -1 };
  return { text: label.slice(0, index) + label.slice(index + 1), key: label[index + 1].toLowerCase(), index };
}
